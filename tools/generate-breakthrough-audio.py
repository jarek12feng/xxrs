"""Original deterministic pentatonic score and accents, no recordings or external samples."""
import array, json, math, wave
from pathlib import Path
root = Path(__file__).resolve().parent.parent
out = root / 'public/audio/breakthrough-v1'
out.mkdir(parents=True, exist_ok=True)
rate = 44100
report = []
for name, seconds, base, score in [('foundation-rise',12,146.83,True),('golden-rise',12,196,True),('breakthrough',3.2,146.83,False),('golden-breakthrough',4,196,False),('nascent-rise',12,220,True),('nascent-breakthrough',4,220,False)]:
    data = [0.0] * int(seconds*rate)
    melody = [0,7,12,14,19,24,19,14,12] if score else [0,7,12,19,24]
    if name.startswith("nascent"):
        melody = [0,12,7,19,24,26,31,24,19] if score else [0,12,19,24,31]
    for k, semitone in enumerate(melody):
        start = k * (0.92 if score else 0.23)
        length = 3.3 if score else 2.5
        frequency = base*2**(semitone/12)
        for i in range(int(length*rate)):
            pos=int(start*rate)+i
            if pos >= len(data): break
            t=i/rate
            envelope=(1-math.exp(-t*35))*math.exp(-t*(1.7 if score else 2.3))
            # Plucked harmonics and a soft bell octave; no noise or random seed.
            sample=math.sin(2*math.pi*frequency*t)+.22*math.sin(4*math.pi*frequency*t)*math.exp(-t*3)+.08*math.sin(6*math.pi*frequency*t)
            data[pos]+=sample*envelope*.19
    if score:
        for i in range(len(data)):
            t=i/rate
            env=min(t/1.4,1)*min((seconds-t)/2.5,1)
            data[i]+=.045*env*(math.sin(2*math.pi*base/2*t)+.5*math.sin(2*math.pi*base*.75*t))
    fade=int(.25*rate)
    for i in range(fade): data[-1-i]*=i/fade
    peak=max(abs(x) for x in data)
    gain=min(1,.65/peak)
    pcm=array.array('h')
    for i,x in enumerate(data):
        pcm.append(round(x*gain*32767))
        pcm.append(round((.92*x + .08*(data[i-220] if i>=220 else 0))*gain*32767))
    with wave.open(str(out/f'{name}.wav'),'wb') as w:
        w.setnchannels(2);w.setsampwidth(2);w.setframerate(rate);w.writeframes(pcm.tobytes())
    report.append({'cue':name,'seconds':seconds,'sampleRate':rate,'peak':round(peak*gain,4),'rms':round(math.sqrt(sum((x*gain)**2 for x in data)/len(data)),4)})
(out/'provenance.json').write_text(json.dumps({'source':'Original procedural composition; generated by tools/generate-breakthrough-audio.py; no third-party samples','files':report},ensure_ascii=False,indent=2)+'\n')
print(json.dumps(report))
