import type { State } from "./world";

// Both companions share choices and costs; their speech and actions stay distinct.
export function companionScene(
  s: State,
  scene: "walk" | "night" | "watch" | "pledge",
) {
  const shen = s.social.gender === "male";
  if (scene === "walk")
    return shen
      ? "雨把沈听澜刚画的路标冲掉了。她沿崖攀住绳索，想量清最后一段石阶，碎石却从脚下滚落。你伸手时，她先将你推回稳处，袖口被石角扯破。“别照旧图走，下面那级空了！”崖下的药工捂着伤腿，她咬住尺绳，将空出的手指向背风处：“我盯着这里。你看伤，或者替我标路。走不快就慢慢来。”"
      : "雨里，引路阵接连熄了两处。尹照川将你推回石阶，自己攀着绳索探向断开的阵纹，袖口在石上划破。他没有立刻接回铜线，先摸清哪一股灵流仍在走。“接错了，下面的人会往崖边去。”他朝受伤药工喊了一声，让人原地等，再转向你：“帮我照看伤者，或把安全路标出来。我在这里稳住灯。”";
  if (scene === "night") {
    const echo =
      {
        care: "那天你替药工敷过药，湿透的药布至今还搭在檐下。",
        mark: "你补下的记号被誊进了路簿，旁边记着最后一人回山的时辰。",
        stay: "那天众人走得很慢，回山时灯都熄了。你们还记得最后一个人跨进门槛的声音。",
      }[s.social.answers.walk ?? "stay"] ?? "";
    return (
      echo +
      (shen
        ? "沈听澜翻开那张泡皱的图，空白处多了几次擦改。“我从前想，把山都画下来就好了。”她用指腹抹去一团墨：“那天挂在崖上，才知道纸画得再大，手撑不住也是白搭。我得闭关一阵。”她把剩下的半块饼推给你：“你呢？下次出关，想先去哪座山？”"
        : "尹照川将裂开的阵盘拆到只剩底座，试了三次才接稳铜线。“靠修修补补，只能走到这里。再远的古阵，我连气都送不进去。”他将工具收好，露出桌上一本久未翻开的经书。“这阵子我想留点时间读它。”茶已经凉了，他没有起身换：“你若也闭关，出关后……来敲一下门。”")
    );
  }
  if (scene === "watch")
    return shen
      ? "沈听澜在台阶下递来一块凉帕，另一只手藏着一张草图。你伸手去看，她先笑了：“本来想画你出招，结果只画成一团墨。你自己说，哪一招最得意？”她往旁边挪了一点，给你留出坐的位置。"
      : "尹照川把茶放在台阶上，握了握你的手，确认虎口没裂，才松开。“我在台下数你的换气，数到后来，倒把自己憋住了。”他有些不好意思，取出记下的几笔：“等你歇过来，一起看看？”";
  const promised = s.social.answers.night === "promise";
  return shen
    ? "沈听澜拿来一张折得很小的归途图。" +
        (promised
          ? "“你说出关来找我，我就把这几条岔路又走了一遍。”"
          : "“你说不定什么时候回来。我还是把路画好了，哪天用得上就用。”") +
        "她指给你看图角的一扇小窗，那是刻印铺的后门。“别只交给别人问路。这张，是给你的。”她的手停在纸边：“下回回来，先来见我，好不好？”"
    : "尹照川将一枚引路木符放进你手心，刻槽里还留着细木屑。" +
        (promised
          ? "“你说出关会来。我还是做了这个，夜里找路方便。”"
          : "“不用定日子。带着这个，哪次想来都找得到。”") +
        "他替你拂掉木屑，却没有马上松手。“我给很多人修过灯。这枚想让你一直带着。你愿意么？”";
}
